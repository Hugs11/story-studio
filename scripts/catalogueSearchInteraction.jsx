// Real browser regression: unified catalogue bar, responsive layout and search focus.
import React from 'react';
import { createRoot } from 'react-dom/client';
import { ErrorDialogProvider } from '../src/components/common/Dialog.jsx';
import { CatalogueBrowser } from '../src/components/Catalogue/CatalogueBrowser.jsx';
import { FicheExemplars } from '../src/components/Catalogue/fiche/FicheDialog.jsx';
import { card } from './catalogueFixtures.mjs';
import { CatalogueCard } from '../src/components/Catalogue/views/CatalogueCard.jsx';
import { CatalogueChrome } from '../src/components/Catalogue/CatalogueChrome.jsx';
import '../src/styles/variables.css';
import '../src/styles/layout.css';
import '../src/components/Catalogue/CatalogueScreen.css';
import { initializeI18n } from '../src/i18n/index.js';
initializeI18n('fr');
const frames = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
const assert = (value, message) => { if (!value) throw new Error(message); };
const renderHeader = controls => <CatalogueChrome {...controls} />;
async function run() {
  const announcements = [];
  const cards = [2, 5, 7, 8].map(age => card({ id: `age-${age}`, title: `Age ${age}`, ageMin: age }));
  const root = createRoot(document.getElementById('surface'));
  root.render(<ErrorDialogProvider><CatalogueBrowser cards={cards} revision={1} api={{}} onAnnounce={notice => announcements.push(notice)} onError={() => {}} renderEmpty={() => null} renderHeader={renderHeader} /></ErrorDialogProvider>);
  await frames();
  await new Promise(resolve => setTimeout(resolve, 100));
  const input = document.getElementById('catalogue-search');
  assert(input.closest('.catalogue-chrome'), 'search belongs to the catalogue bar');
  const bar = document.querySelector('.catalogue-chrome');
  const center = bar.querySelector('.chrome-toolbar-center').getBoundingClientRect();
  const right = bar.querySelector('.chrome-toolbar-right').getBoundingClientRect();
  assert(document.documentElement.scrollWidth <= window.innerWidth, 'toolbar does not overflow the viewport');
  if (window.innerWidth > 1100) assert(Math.abs((center.top + center.bottom) / 2 - (right.top + right.bottom) / 2) < 2, 'wide bar keeps controls on one row');
  else assert(center.top >= right.bottom, 'narrow bar moves search below the other controls');
  assert(input.getBoundingClientRect().width >= 150, 'search retains usable width');
  const checkHeights = () => {
    const searchHeight = bar.querySelector('.catalogue-search').getBoundingClientRect().height;
    for (const control of bar.querySelectorAll('.catalogue-filter-trigger, .catalogue-sort, .media-view-switch, .me-col-picker-btn, .chrome-toolbar-btn')) {
      assert(Math.abs(control.getBoundingClientRect().height - searchHeight) < 1, `control height matches search: ${control.className}`);
    }
  };
  checkHeights();
  [...bar.querySelectorAll('.media-view-switch button')].at(-1).click();
  await frames();
  assert(bar.querySelector('.me-col-picker-btn'), 'list exposes its column picker');
  checkHeights();
  window.dispatchEvent(new KeyboardEvent('keydown', { key: 'f', code: 'KeyF', ctrlKey: true, bubbles: true, cancelable: true }));
  await frames();
  assert(document.activeElement === input, 'shortcut focuses visible search');
  root.render(<ErrorDialogProvider><CatalogueBrowser cards={cards} revision={2} api={{}} onAnnounce={notice => announcements.push(notice)} onError={() => {}} renderEmpty={() => null} renderHeader={renderHeader} /></ErrorDialogProvider>);
  await frames();
  assert(document.activeElement === input, 'parent rerender retains search focus');
  const selectable = document.querySelector('[data-card-id]');
  selectable.click();
  await frames();
  assert(document.querySelector('[data-card-id][aria-selected="true"]'), 'a fiche is selected before filtering');
  const setInput = value => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  };
  setInput('no matching catalogue fiche');
  await frames();
  assert(!document.querySelector('[data-card-id][aria-selected="true"]'), 'filtering removes hidden fiches from selection');
  assert(!announcements.some(notice => notice.key.startsWith('catalogue:selection.hidden.')), 'selection pruning produces no notification');
  setInput('');
  await frames();
  document.querySelector('.catalogue-row button.catalogue-filter-badge').click();
  await frames();
  assert(document.querySelectorAll('[data-card-id]').length === 1, 'clicking the age filters out packs requiring an older child');
  assert(bar.querySelector('.catalogue-age-trigger')?.textContent.includes('2 ans'), 'age click creates an exact 2-year age');
  bar.querySelector('.catalogue-age-trigger [aria-haspopup]').click();
  await frames();
  const ageInputs = [...bar.querySelectorAll('.catalogue-age-range input')];
  assert(ageInputs.length === 2 && ageInputs.every(control => control.value === '2'), 'age editor exposes two prefilled bounds');
  const changeAge = (control, value) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(control, value);
    control.dispatchEvent(new Event('input', { bubbles: true }));
  };
  changeAge(ageInputs[1], '7'); await frames();
  changeAge(ageInputs[0], '3'); await frames();
  assert(document.querySelectorAll('[data-card-id]').length === 2, 'editing valid age bounds applies immediately');
  assert(bar.querySelector('.catalogue-age-editor').getBoundingClientRect().right <= window.innerWidth, 'age range editor fits the viewport');
  changeAge(ageInputs[0], '8'); await frames();
  assert(bar.querySelector('.catalogue-age-editor [role="alert"]') && ageInputs.every(control => control.getAttribute('aria-invalid') === 'true'), 'invalid bounds stay editable with a local error');
  assert(document.querySelectorAll('[data-card-id]').length === 2, 'invalid bounds preserve the last valid filter');
  changeAge(ageInputs[0], '3'); await frames();
  assert(document.querySelectorAll('[data-card-id]').length === 2, '3–7 range keeps packs from 5 and 7 and excludes 2 and 8');
  assert(bar.querySelector('.catalogue-age-trigger').textContent.includes('3 à 7 ans'), 'chip reflects both applied age bounds');
  bar.querySelector('.catalogue-age-footer button').click();
  bar.querySelector('.catalogue-age-trigger [aria-haspopup]').click();
  await frames();
  assert(!bar.querySelector('.catalogue-filter-line'), 'bar starts compact without active filters');
  const compactHeight = bar.getBoundingClientRect().height;
  bar.querySelector('.catalogue-filter-trigger').click();
  await frames();
  bar.querySelector('.catalogue-toolbar .project-menu-item').click();
  await frames();
  const filterLine = bar.querySelector('.catalogue-filter-line');
  assert(filterLine, 'active filters belong to the catalogue bar');
  const search = bar.querySelector('.catalogue-search').getBoundingClientRect();
  const filters = filterLine.getBoundingClientRect();
  assert(Math.abs(filters.left - search.left) < 1, 'filters align with the search');
  assert(filters.top >= search.bottom, 'filters are below search');
  assert(bar.getBoundingClientRect().height > compactHeight, 'active filters increase the bar height');
  assert(document.documentElement.scrollWidth <= window.innerWidth, 'active filters do not overflow the viewport');
  bar.querySelector('.catalogue-filter-summary > button').click();
  await frames();
  assert(!bar.querySelector('.catalogue-filter-line'), 'clearing filters removes their row');
  assert(Math.abs(bar.getBoundingClientRect().height - compactHeight) < 1, 'clearing filters restores compact height');
  root.unmount();
  const inspector = createRoot(document.getElementById('surface'));
  const sample = card({ id: 'copies-alignment', exemplars: ['project', 'zip', 'sevenZip', 'folder'].map((format, index) => ({ id: `copy-${index}`, format })) });
  inspector.render(<ErrorDialogProvider><div className="catalogue-browser"><aside className="catalogue-fiche" style={{ width: 480, maxWidth: '100%' }}><div className="catalogue-fiche-content"><FicheExemplars card={sample} /></div></aside></div></ErrorDialogProvider>);
  await frames();
  const heading = document.getElementById('catalogue-fiche-copies-title');
  const list = document.getElementById('catalogue-fiche-copies');
  assert(heading.querySelector('.catalogue-fiche-copies-count')?.textContent === '4', 'copy count has a separate badge');
  assert(getComputedStyle(list).paddingInlineStart === '0px', 'copy list overrides generic list indentation');
  const bounds = list.getBoundingClientRect();
  for (const row of list.children) {
    const rect = row.getBoundingClientRect();
    assert(Math.abs(rect.left - heading.getBoundingClientRect().left) < 1, 'copy cards align with the section heading');
    assert(Math.abs(rect.right - bounds.right) < 1, 'copy cards use the full list width');
  }
  inspector.unmount();
  const badgesRoot = createRoot(document.getElementById('surface'));
  const tagged = card({ id: 'responsive-tags', title: 'Étiquettes', ageMin: 3, tags: [{ id: 'ccc', label: 'ccc' }, { id: 'qqq', label: 'qqq' }] });
  const tagFilters = [], ages = []; let selected = 0;
  const badgeView = { activeId: tagged.id, selected: new Set(), onFilterTag: id => tagFilters.push(id), onFilterAge: age => ages.push(age), onItemClick: () => selected++, setActiveId() {} };
  const renderBadges = width => badgesRoot.render(<div className="catalogue-browser" style={{ width }}><CatalogueCard item={{ card: tagged, exemplars: tagged.exemplars }} index={0} view={badgeView} /></div>);
  renderBadges(320); await frames(); await frames();
  const directTags = () => [...document.querySelectorAll('button.catalogue-card-tag-indicator--single')];
  assert(directTags().length === 2 && !document.querySelector('button.catalogue-card-tag-overflow'), 'two short tags stay visible when they fit');
  const ageBadge = document.querySelector('button.catalogue-card-age');
  for (const tag of directTags()) {
    const style = getComputedStyle(tag), ageStyle = getComputedStyle(ageBadge);
    for (const property of ['height', 'borderRadius', 'backgroundColor', 'borderTopWidth', 'borderTopColor']) assert(style[property] === ageStyle[property], `age and tags share ${property}`);
  }
  directTags()[0].click(); ageBadge.click();
  assert(tagFilters[0] === 'ccc' && ages[0] === 3 && selected === 0, 'age and tag clicks filter without selecting the fiche');
  renderBadges(180); await frames(); await frames();
  const overflow = document.querySelector('button.catalogue-card-tag-overflow');
  assert(overflow, 'narrow card moves overflowing tags into a menu');
  overflow.click(); await frames();
  const tagMenu = document.querySelector('.catalogue-card-tags-menu');
  assert(tagMenu && tagMenu.querySelectorAll('[role="menuitem"]').length > 0, 'overflow menu exposes hidden tags');
  const menuItem = tagMenu.querySelector('button');
  const surfaceProbe = document.createElement('span');
  surfaceProbe.style.background = menuItem.matches(':hover, :focus-visible') ? 'var(--control-bg-hover)' : 'transparent';
  tagMenu.append(surfaceProbe);
  assert(getComputedStyle(menuItem).backgroundColor === getComputedStyle(surfaceProbe).backgroundColor && getComputedStyle(menuItem).appearance === 'none', 'tag menu buttons use catalogue surfaces rather than native button fill');
  surfaceProbe.remove();
  menuItem.click(); await frames();
  assert(tagFilters.length === 2 && !document.querySelector('.catalogue-card-tags-menu'), 'overflow tag tagFilters and closes the menu');
  renderBadges(320); await frames(); await frames();
  assert(directTags().length === 2 && !document.querySelector('button.catalogue-card-tag-overflow'), 'tags return inline when the card grows');
  tagged.tags = [{ id: 'long', label: 'Une étiquette beaucoup plus longue que la place disponible sur la vignette' }];
  renderBadges(320); await frames(); await frames();
  assert(directTags().length === 0, 'a long label is not truncated into a direct filter');
  const longOverflow = document.querySelector('button.catalogue-card-tag-overflow');
  assert(longOverflow, 'a single long tag also gets accessible overflow');
  longOverflow.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true, cancelable: true }));
  await frames();
  const longMenu = document.querySelector('.catalogue-card-tags-menu');
  assert(longMenu?.textContent === tagged.tags[0].label, 'long tag menu keeps the complete label');
  assert(longMenu.getBoundingClientRect().right <= window.innerWidth, 'long menu stays inside the viewport');
  longMenu.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }));
  await frames();
  assert(!document.querySelector('.catalogue-card-tags-menu') && document.activeElement === longOverflow, 'Escape closes overflow and restores focus');
  badgesRoot.unmount();
  globalThis.dump('CATALOGUE_INTERACTION_OK\n');
}
run().catch(error => globalThis.dump(`CATALOGUE_INTERACTION_ERROR ${error.message} ${error.stack}\n`));
